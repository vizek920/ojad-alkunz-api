// ── POST /api/sessions ────────────────────────────────────────────────────────
router.post('/', async (req, res) => {
  try {
    const {
      name,
      password,
      is_private = false,
      max_viewers = 50,
      team1_name = 'الفريق الأول',
      team2_name = 'الفريق الثاني',
      stage_count = 15,
    } = req.body;

    if (!name) return res.status(400).json({ error: 'اسم الجلسة مطلوب' });
    if (!password) return res.status(400).json({ error: 'كلمة المرور مطلوبة' });

    // Create session (code generated by DB trigger)
    const { data: session, error: sErr } = await supabase
      .from('sessions')
      .insert({
        name,
        password,
        is_private,
        max_viewers,
        status: 'active',
        host_last_seen: new Date().toISOString(),
      })
      .select()
      .single();

    if (sErr) throw sErr;

    // Create two teams
    const { error: tErr } = await supabase.from('session_teams').insert([
      { session_id: session.id, team_key: 'team1', name: team1_name, score: 0, lives: 2 },
      { session_id: session.id, team_key: 'team2', name: team2_name, score: 0, lives: 2 },
    ]);
    if (tErr) throw tErr;

    // Create stages
    const stages = Array.from({ length: stage_count }, (_, i) => ({
      session_id: session.id,
      stage_number: i + 1,
      status: i === 0 ? 'active' : 'pending',
    }));
    const { error: stErr } = await supabase.from('session_stages').insert(stages);
    if (stErr) throw stErr;

    res.status(201).json({ session });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// ── POST /api/sessions/:id/validate ──────────────────────────────────────────
router.post('/:id/validate', async (req, res) => {
  try {
    const { password } = req.body;
    if (!password) return res.status(400).json({ error: 'كلمة المرور مطلوبة' });

    const { data: session, error } = await supabase
      .from('sessions')
      .select('*')
      .eq('id', req.params.id)
      .single();

    if (error || !session) return res.status(404).json({ error: 'الجلسة غير موجودة' });
    if (session.password !== password) return res.status(401).json({ error: 'كلمة المرور غير صحيحة' });

    res.json({ session });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

